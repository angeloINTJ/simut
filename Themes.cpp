const int NUM_THEMES = sizeof(availableThemes) / sizeof(ThemePalette);

/** @brief Load a theme by index into the active palette. */
void loadTheme(int index) {
    if(index < 0 || index >= NUM_THEMES) index = 0;
    currentTheme = availableThemes[index];
}

int getThemeCount() { return NUM_THEMES; }

String getThemeId(int index) {
    if(index < 0 || index >= NUM_THEMES) return "";
    return String(availableThemes[index].idName);
}

/** @brief Find a theme by name (exact match first, then substring search). */
int getThemeIndexByName(String name) {
    for(int i=0; i<NUM_THEMES; i++) {
        if (String(availableThemes[i].idName).equalsIgnoreCase(name)) return i;
    }
    for(int i=0; i<NUM_THEMES; i++) {
        if (String(availableThemes[i].idName).indexOf(name) >= 0) return i;
    }
    return -1;
}
