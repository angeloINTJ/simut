#!/usr/bin/env python3
"""fonte_web.py -- writes the font block of the web page's live LCD view into WebUI.h, and checks it (2026-11-04).

The alpha's live LCD view (GET /api/lcd and the box on the dashboard) draws the glass in a canvas, and the canvas needs the dots of every
character. They are the X.Org misc-fixed 5x7, public domain, as tools/lcd_alpha/fonte_x11.py holds them (generated from the font files by
fonte_extract.py): the maintainer chose it, on 2026-11-04, so that the Hitachi ROM table (rom_hd44780.py, for the manual's figures only)
never ships inside an image. This tool turns FONTE_5X7 into the block of WebUI.h that sits between

    /* @LCD_FONT_BEGIN (generated by tools/lcd_alpha/fonte_web.py) */      and      /* @LCD_FONT_END */

inside the JS of the dashboard's `@IF lcd` block. The block is a generated file in the middle of a hand-written one: never edit it, run --write.

The encoding is one string of hex digits: the codes 0x20 to 0x7F in order, seven rows of each (row 7 of the 5 x 8 cell is the cursor row and
is 0 in all 96 glyphs, so it is not sent: the page puts a 0 there), two upper-case digits a row, row 0 on top, bit 4 the leftmost dot. 96 x 7 x 2
= 1344 digits, written as six strings of 16 glyphs and joined by the page. The encoder REFUSES what the page could not draw: a code missing, a
code past 0x7F, a row that does not fit 5 dots and, above all, a row 7 that is not 0 (it would be dropped without a word).

  python3 tools/lcd_alpha/fonte_web.py --check [--webui WebUI.h]    exit 0 when the block is what fonte_x11.py says, 1 when it differs or its markers are not
                                                                    there exactly once (a finding), 2 when it cannot run (a file missing)
  python3 tools/lcd_alpha/fonte_web.py --write [--webui WebUI.h]    puts the block between the markers; exit 0 written, 1 when the markers are not there, 2 as above

tools/lcd_alpha/test_lcd_js.py holds this tool (the checks on copies of WebUI.h, the encoder's refusals) and the page's renderer against lcd.py.
Standard library only. Python 3.11 and later.
"""
import argparse
import difflib
import pathlib
import sys

sys.dont_write_bytecode = True
HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parents[1]
sys.path.insert(0, str(HERE))        # explicit: python3 -I leaves the script's own folder off the path (fonte_x11.py)

BEGIN = '/* @LCD_FONT_BEGIN (generated by tools/lcd_alpha/fonte_web.py) */'
END = '/* @LCD_FONT_END */'
PRIMEIRO, ULTIMO = 0x20, 0x7F
LINHAS = 7            # rows sent for each glyph; the 8th is 0 and the page supplies it
POR_TEXTO = 16        # glyphs in each string of the block
RECUO = ' ' * 8       # the block sits 8 columns in, inside the <script> of DASH_PAGE


def codificar(tabela):
    """The 1344 hex digits of a table {code: 8 rows}: codes 0x20 to 0x7F, 7 rows each, two upper-case digits a row. ValueError, naming the code,
    for a code missing or past 0x7F, a glyph that is not 8 integers, a row that does not fit 5 dots and a row 7 that is not 0."""
    for c in sorted(tabela):
        if not PRIMEIRO <= c <= ULTIMO:
            raise ValueError(f'code 0x{c:02X} is past 0x{ULTIMO:02X}: the page has 96 glyphs, 0x{PRIMEIRO:02X} to 0x{ULTIMO:02X}')
    saida = []
    for c in range(PRIMEIRO, ULTIMO + 1):
        if c not in tabela:
            raise ValueError(f'code 0x{c:02X} is missing from the table')
        g = tabela[c]
        if len(g) != 8 or not all(isinstance(v, int) and not isinstance(v, bool) for v in g):
            raise ValueError(f'the glyph of code 0x{c:02X} is not 8 integer rows')
        if g[7] != 0:
            raise ValueError(f'row 7 of code 0x{c:02X} is {g[7]}, not 0: the block sends 7 rows and the page puts a 0 in the eighth, so this dot would be lost')
        for i in range(LINHAS):
            if not 0 <= g[i] <= 0x1F:
                raise ValueError(f'row {i} of code 0x{c:02X} is 0x{g[i]:02X}: it does not fit the 5 dots (0x00 to 0x1F)')
            saida.append(f'{g[i]:02X}')
    return ''.join(saida)


def bloco(tabela, pino):
    """The text from the begin marker to the end marker, as it stands in WebUI.h (the first line's indentation is the file's own)."""
    h = codificar(tabela)
    por = POR_TEXTO * LINHAS * 2
    linhas = [h[i:i + por] for i in range(0, len(h), por)]
    corpo = [f"{RECUO}    '{t}'" + (',' if k < len(linhas) - 1 else '') + f'   /* 0x{PRIMEIRO + k * POR_TEXTO:02X}-0x{PRIMEIRO + k * POR_TEXTO + POR_TEXTO - 1:02X} */'
             for k, t in enumerate(linhas)]
    return '\n'.join([
        BEGIN,
        f'{RECUO}/* GENERATED from tools/lcd_alpha/fonte_x11.py by tools/lcd_alpha/fonte_web.py: never edit by hand, run fonte_web.py --write.',
        f'{RECUO}   The X.Org misc-fixed 5x7, public domain ("Public domain font.  Share and enjoy."); fonte_x11.py TABLE_SHA256 {pino}.',
        f'{RECUO}   Codes 0x20 to 0x7F, seven rows each (row 7 of the 5 x 8 cell is always 0 and is not sent), two hex digits a row, row 0 on top,',
        f'{RECUO}   bit 4 the leftmost dot: six strings of 16 glyphs (224 digits). The Hitachi ROM table is not in the page. */',
        f'{RECUO}const LCD_FONT_HEX = [',
        *corpo,
        f"{RECUO}].join('');",
        f'{RECUO}{END}',
    ])


def ler(caminho):
    with open(caminho, encoding='utf-8', newline='') as f:
        return f.read()


def achar(texto):
    """(start of the begin marker, end of the end marker) when each marker is there once and in order, else None."""
    if texto.count(BEGIN) != 1 or texto.count(END) != 1:
        return None
    i, j = texto.find(BEGIN), texto.find(END)
    return (i, j + len(END)) if i < j else None


def main(argv=None):
    ap = argparse.ArgumentParser(description="Writes and checks the font block of the web page's live LCD view in WebUI.h.")
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument('--check', action='store_true', help='exit 0 when the block is what fonte_x11.py says')
    g.add_argument('--write', action='store_true', help='put the block between the markers')
    ap.add_argument('--webui', default=str(REPO / 'WebUI.h'), help='the file to read and write (default: the tree\'s WebUI.h)')
    a = ap.parse_args(argv)
    try:
        import fonte_x11
        texto = ler(a.webui)
    except (ImportError, OSError) as e:
        print(f'fonte_web.py: cannot run: {e}', file=sys.stderr)
        return 2
    try:
        novo = bloco(fonte_x11.FONTE_5X7, fonte_x11.TABLE_SHA256)
    except ValueError as e:
        print(f'fonte_web.py: fonte_x11.py cannot be sent to the page: {e}', file=sys.stderr)
        return 2
    lugar = achar(texto)
    if lugar is None:
        print(f'fonte_web.py: {a.webui} does not have {BEGIN!r} and {END!r} once each, in that order', file=sys.stderr)
        return 1
    atual = texto[lugar[0]:lugar[1]]
    if a.check:
        if atual == novo:
            print(f'fonte_web.py: the font block of {a.webui} is what fonte_x11.py says (96 glyphs, 1344 digits, table sha256 {fonte_x11.TABLE_SHA256[:16]}...)')
            return 0
        d = list(difflib.unified_diff(atual.split('\n'), novo.split('\n'), 'WebUI.h', 'fonte_x11.py', lineterm='', n=0))
        print('fonte_web.py: the font block of ' + a.webui + ' is not what fonte_x11.py says; run: python3 tools/lcd_alpha/fonte_web.py --write', file=sys.stderr)
        for linha in d[:8]:
            print('  ' + (linha if len(linha) < 150 else linha[:147] + '...'), file=sys.stderr)
        return 1
    if atual != novo:
        with open(a.webui, 'w', encoding='utf-8', newline='') as f:
            f.write(texto[:lugar[0]] + novo + texto[lugar[1]:])
        print(f'fonte_web.py: wrote the font block into {a.webui}')
    else:
        print(f'fonte_web.py: {a.webui} already has the block')
    return 0


if __name__ == '__main__':
    sys.exit(main())
