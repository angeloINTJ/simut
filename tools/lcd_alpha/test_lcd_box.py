def roda(codigo):
    """{case: [failures]} from the scenarios run on `codigo`, or (None, why)."""
    with tempfile.TemporaryDirectory(prefix='test_lcd_box_') as tmp:
        tmp = pathlib.Path(tmp)
        (tmp / 'code.js').write_text(codigo, encoding='utf-8')
        (tmp / 'run.js').write_text(DRIVER, encoding='utf-8')
        r = subprocess.run([node(), str(tmp / 'run.js'), str(tmp / 'code.js')], capture_output=True, text=True, timeout=180)
        if r.returncode != 0:
            return None, (r.stderr or r.stdout)[-1500:]
        try:
            return json.loads(r.stdout.strip().splitlines()[-1]), None
        except (ValueError, IndexError):
            return None, 'node printed no result: ' + (r.stdout + r.stderr)[-600:]


def confere_cenarios(rotulo, codigo):
    res, erro = roda(codigo)
    if res is None:
        return confere(False, f'{rotulo}: node runs the box', str(erro))
    ok = True
    for nome, fails in res.items():
        ok &= confere(not fails, f'{rotulo}: {nome}' + (f' ({len(fails)} findings)' if fails else ''), '; '.join(fails[:3]))
    return ok


