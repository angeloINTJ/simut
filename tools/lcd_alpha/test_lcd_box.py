def corte(src, a, b):
    if src.count(a) != 1 or src.count(b) != 1 or src.find(a) > src.find(b):
        return None
    return src[src.find(a):src.find(b) + len(b)]


def blocos_lcd(src):
    """The bodies of the /* @IF lcd */ blocks of DASH_PAGE, in file order."""
    ini = src.find('static const char DASH_PAGE[]')
    fim = src.find(')raw";', ini)
    pag = src[ini:fim]
    return [m.group(1) for m in re.finditer(r'[ \t]*/\*\s*@IF\s+lcd\s*\*/[^\n]*\n(.*?)[ \t]*/\*\s*@ENDIF\s*\*/', pag, re.S)]


def sem_comentarios(js):
    return re.sub(r'/\*.*?\*/', ' ', js, flags=re.S)


def webdict(pack):
    linhas = pack.read_text(encoding='utf-8').split('\n')
    return json.loads(linhas[linhas.index('@WEBDICT') + 1])


